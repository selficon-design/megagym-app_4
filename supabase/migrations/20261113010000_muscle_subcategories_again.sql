-- ΦΟΡΜΑ — «Αύξηση μυϊκού ιστού»: ξανά «ΓΕΝΙΚΟ» όσα σώθηκαν χωρίς υποκατηγορία
--   ΑΝΔΡΕΣ:   ΓΕΝΙΚΟ · ΕΜΦΑΣΗ ΣΤΟ ΠΑΝΩ ΣΩΜΑ
--   ΓΥΝΑΙΚΕΣ: ΓΕΝΙΚΟ · ΕΜΦΑΣΗ ΣΤΟ ΚΑΤΩ ΣΩΜΑ
-- Τα υπάρχοντα προγράμματα «Αύξηση μυϊκού ιστού» (χωρίς υποκατηγορία) γίνονται «ΓΕΝΙΚΟ».
-- Η τρέχουσα ζωντανή εφαρμογή (index.html) δεν επηρεάζεται: εκεί η κατηγορία δεν έχει υποκατηγορίες
-- και δείχνει όλα τα προγράμματά της ανεξάρτητα από την υποκατηγορία.
-- Μπορεί να ξανατρέξει χωρίς πρόβλημα.
-- =====================================================================
update public.template_programs
   set sub_category = 'ΓΕΝΙΚΟ'
 where top_category = 'ΑΥΞΗΣΗ ΜΥΙΚΟΥ ΙΣΤΟΥ'
   and coalesce(sub_category, '') = '';
