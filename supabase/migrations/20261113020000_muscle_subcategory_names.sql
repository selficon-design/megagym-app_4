-- =====================================================================
-- ΦΟΡΜΑ — Ονόματα υποκατηγοριών «Αύξηση μυϊκού ιστού» (όπως τα θέλει ο ιδιοκτήτης)
--   ΓΕΝΙΚΟ                 → ΓΥΜΝΑΖΕΙ ΟΛΟ ΤΟ ΣΩΜΑ
--   ΕΜΦΑΣΗ ΣΤΟ ΠΑΝΩ ΣΩΜΑ  → ΜΕ ΕΜΦΑΣΗ ΣΤΟ ΠΑΝΩ ΜΕΡΟΣ ΤΟΥ ΣΩΜΑΤΟΣ (άνδρες)
--   ΕΜΦΑΣΗ ΣΤΟ ΚΑΤΩ ΣΩΜΑ  → ΜΕ ΕΜΦΑΣΗ ΣΤΟ ΚΑΤΩ ΜΕΡΟΣ ΤΟΥ ΣΩΜΑΤΟΣ (γυναίκες)
-- Ισχύει για τα έτοιμα προγράμματα και για τις κάρτες κατηγοριών της βιβλιοθήκης. Μπορεί να ξανατρέξει.
-- =====================================================================
update public.template_programs set sub_category = case
    when coalesce(sub_category,'') in ('', 'ΓΕΝΙΚΟ') then 'ΓΥΜΝΑΖΕΙ ΟΛΟ ΤΟ ΣΩΜΑ'
    when sub_category = 'ΕΜΦΑΣΗ ΣΤΟ ΠΑΝΩ ΣΩΜΑ' then 'ΜΕ ΕΜΦΑΣΗ ΣΤΟ ΠΑΝΩ ΜΕΡΟΣ ΤΟΥ ΣΩΜΑΤΟΣ'
    when sub_category = 'ΕΜΦΑΣΗ ΣΤΟ ΚΑΤΩ ΣΩΜΑ' then 'ΜΕ ΕΜΦΑΣΗ ΣΤΟ ΚΑΤΩ ΜΕΡΟΣ ΤΟΥ ΣΩΜΑΤΟΣ'
    else sub_category end
 where top_category = 'ΑΥΞΗΣΗ ΜΥΙΚΟΥ ΙΣΤΟΥ';

-- Κάρτες κατηγοριών: μετονομασία μόνο αν δεν υπάρχει ήδη κάρτα με το νέο όνομα
update public.library_categories c set sub_category = case c.sub_category
    when 'ΓΕΝΙΚΟ' then 'ΓΥΜΝΑΖΕΙ ΟΛΟ ΤΟ ΣΩΜΑ'
    when 'ΕΜΦΑΣΗ ΣΤΟ ΠΑΝΩ ΣΩΜΑ' then 'ΜΕ ΕΜΦΑΣΗ ΣΤΟ ΠΑΝΩ ΜΕΡΟΣ ΤΟΥ ΣΩΜΑΤΟΣ'
    when 'ΕΜΦΑΣΗ ΣΤΟ ΚΑΤΩ ΣΩΜΑ' then 'ΜΕ ΕΜΦΑΣΗ ΣΤΟ ΚΑΤΩ ΜΕΡΟΣ ΤΟΥ ΣΩΜΑΤΟΣ' end
 where c.top_category = 'ΑΥΞΗΣΗ ΜΥΙΚΟΥ ΙΣΤΟΥ'
   and c.sub_category in ('ΓΕΝΙΚΟ','ΕΜΦΑΣΗ ΣΤΟ ΠΑΝΩ ΣΩΜΑ','ΕΜΦΑΣΗ ΣΤΟ ΚΑΤΩ ΣΩΜΑ')
   and not exists (select 1 from public.library_categories x
                   where x.gender = c.gender and x.top_category = c.top_category
                     and x.sub_category = case c.sub_category
                        when 'ΓΕΝΙΚΟ' then 'ΓΥΜΝΑΖΕΙ ΟΛΟ ΤΟ ΣΩΜΑ'
                        when 'ΕΜΦΑΣΗ ΣΤΟ ΠΑΝΩ ΣΩΜΑ' then 'ΜΕ ΕΜΦΑΣΗ ΣΤΟ ΠΑΝΩ ΜΕΡΟΣ ΤΟΥ ΣΩΜΑΤΟΣ'
                        when 'ΕΜΦΑΣΗ ΣΤΟ ΚΑΤΩ ΣΩΜΑ' then 'ΜΕ ΕΜΦΑΣΗ ΣΤΟ ΚΑΤΩ ΜΕΡΟΣ ΤΟΥ ΣΩΜΑΤΟΣ' end);
