create table if not exists public.foods (
  id            uuid primary key default gen_random_uuid(),
  name          text not null,
  category      text not null default 'Άλλο',
  kcal          numeric(6,1) not null check (kcal >= 0),       -- ανά 100γρ. (ή 100ml)
  protein_g     numeric(5,1) not null default 0 check (protein_g >= 0),
  carbs_g       numeric(5,1) not null default 0 check (carbs_g >= 0),
  fat_g         numeric(5,1) not null default 0 check (fat_g >= 0),
  portion_label text,                                            -- π.χ. '1 αυγό'
  portion_grams numeric(6,1) check (portion_grams is null or portion_grams > 0),
  created_by    uuid default auth.uid() references auth.users(id) on delete set null,
  updated_at    timestamptz not null default now(),
  created_at    timestamptz not null default now()
);
create unique index if not exists foods_name_unique on public.foods (lower(name));

alter table public.foods enable row level security;

-- Όλοι οι συνδεδεμένοι χρήστες (πελάτες & προπονητές) διαβάζουν τη λίστα
drop policy if exists "foods read" on public.foods;
create policy "foods read" on public.foods
  for select to authenticated using (true);

-- Μόνο ο owner προσθέτει / διορθώνει / σβήνει
drop policy if exists "foods owner insert" on public.foods;
create policy "foods owner insert" on public.foods
  for insert with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'owner'));

drop policy if exists "foods owner update" on public.foods;
create policy "foods owner update" on public.foods
  for update using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'owner'))
  with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'owner'));

drop policy if exists "foods owner delete" on public.foods;
create policy "foods owner delete" on public.foods
  for delete using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'owner'));

